namespace MarketPulse.SharedKernel.DataQuality;

/// <summary>Data-quality statuses from spec §7.1. Persisted as tinyint; values must never be renumbered.</summary>
public enum DataQualityStatus : byte
{
    Healthy = 1,
    Delayed = 2,
    Stale = 3,
    Missing = 4,
    Partial = 5,
    Reconciled = 6,
    Unverified = 7,
    ProviderUnavailable = 8,
}

/// <summary>How data is delivered under the provider contract. Persisted as tinyint; never renumber.</summary>
public enum DeliveryMode : byte
{
    /// <summary>Real-time under a licence that permits real-time display.</summary>
    Live = 1,

    /// <summary>Delayed by a provider-defined interval.</summary>
    Delayed = 2,

    /// <summary>End-of-day / periodic publication (disclosures, fundamentals, EOD candles).</summary>
    EndOfDay = 3,

    /// <summary>Generated by the mock provider. Must never be shown as live.</summary>
    Simulated = 4,
}
